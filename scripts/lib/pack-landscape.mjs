// Shared back end for the landscape data generators. Each generator supplies a
// window and a way to read elevation at a point; this samples that onto a
// regular grid, packs it small enough to ship inside the bundle, and writes the
// module src/lib/electromagnetism/<name>Elevation.ts.

import { writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import { join } from 'node:path';

/**
 * @param options.name          module basename, e.g. 'hakone'
 * @param options.centre        { latitude, longitude } of the window centre
 * @param options.halfEast      metres east of centre the window reaches
 * @param options.halfNorth     metres north of centre the window reaches
 * @param options.columns       grid columns (aspect should match halfEast/halfNorth)
 * @param options.rows          grid rows
 * @param options.sourceMetres  metres between source samples, for the averaging window
 * @param options.elevation     async (east, north) => metres
 * @param options.header        provenance lines for the top of the module
 */
export async function packLandscape(options) {
  const { name, centre, halfEast, halfNorth, columns, rows, sourceMetres, elevation, header } = options;
  const cellEast = halfEast * 2 / (columns - 1), cellNorth = halfNorth * 2 / (rows - 1);
  // Average the source over each output cell rather than point-sampling it. A
  // point sample of a cell many source samples wide aliases, and aliased ground
  // makes ragged contours.
  const acrossEast = Math.max(1, Math.round(cellEast / sourceMetres));
  const acrossNorth = Math.max(1, Math.round(cellNorth / sourceMetres));
  const metres = new Int16Array(columns * rows);
  for (let row = 0; row < rows; row++) {
    for (let column = 0; column < columns; column++) {
      const east = column * cellEast - halfEast, north = halfNorth - row * cellNorth;
      let total = 0, count = 0;
      for (let j = 0; j < acrossNorth; j++) for (let i = 0; i < acrossEast; i++) {
        total += await elevation(east + (i / acrossEast - 0.5) * cellEast,
          north + (j / acrossNorth - 0.5) * cellNorth);
        count++;
      }
      metres[row * columns + column] = Math.round(total / count);
    }
  }

  // Along-row differences, which is what makes a smooth height field compress.
  const deltas = new Int16Array(columns * rows);
  for (let row = 0; row < rows; row++) for (let column = 0; column < columns; column++) {
    const i = row * columns + column;
    deltas[i] = column ? metres[i] - metres[i - 1] : (row ? metres[i] - metres[i - columns] : metres[i]);
  }
  const encoded = Buffer.from(deltas.buffer).toString('base64');
  let lowest = Infinity, highest = -Infinity;
  for (const v of metres) { lowest = Math.min(lowest, v); highest = Math.max(highest, v); }

  const out = join(process.cwd(), 'src', 'lib', 'electromagnetism', `${name}Elevation.ts`);
  writeFileSync(out, `// GENERATED by scripts/build-${name}-terrain.mjs — do not edit by hand.
//
${header.trim().split('\n').map(line => `// ${line}`.trimEnd()).join('\n')}
//
// Sampled onto ${columns} by ${rows} cells of ${Math.round(cellEast)} m by area averaging.
// Ground runs from ${lowest} m to ${highest} m.

export const CENTRE = { latitude: ${centre.latitude}, longitude: ${centre.longitude} };
export const HALF_EAST_METRES = ${halfEast};
export const HALF_NORTH_METRES = ${halfNorth};
export const COLUMNS = ${columns};
export const ROWS = ${rows};
export const LOWEST_METRES = ${lowest};
export const HIGHEST_METRES = ${highest};

/** Row-wise differences of the Int16 height field, little-endian, base64. */
const PACKED = '${encoded}';

/** Undo the packing: base64 to Int16 differences to absolute metres. */
export function decodeElevations(): Int16Array {
  const binary = typeof atob === 'function'
    ? atob(PACKED) : Buffer.from(PACKED, 'base64').toString('binary');
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  const metres = new Int16Array(bytes.buffer, bytes.byteOffset, bytes.length / 2);
  for (let row = 0; row < ROWS; row++) for (let column = 0; column < COLUMNS; column++) {
    const i = row * COLUMNS + column;
    if (column) metres[i] += metres[i - 1];
    else if (row) metres[i] += metres[i - COLUMNS];
  }
  return metres;
}
`);
  console.log(`wrote ${out}`);
  console.log(`${columns}x${rows} cells at ${Math.round(cellEast)} m, ${lowest}-${highest} m`);
  console.log(`packed ${(encoded.length / 1024).toFixed(1)} KB base64`,
    `(${(deflateSync(Buffer.from(deltas.buffer), { level: 9 }).length / 1024).toFixed(1)} KB gzipped over the wire)`);
  return { metres, lowest, highest, cellEast, cellNorth };
}
